#!/usr/bin/env bash
# Installs shirabe's pre-commit hook in this clone. niwa runs it during apply.
#
# niwa runs every executable file in a clone's scripts/setup/ on each create,
# apply and provisioning run, with the clone root as the working directory.
# This file is the same, byte for byte, in every repository that carries it;
# the canonical copy is scripts/setup/shirabe-pre-commit.sh in shirabe.
#
# It prints at most one line and decides, in this order:
#   1. no shirabe on PATH outside this clone: a notice, exit 0
#   2. the hooks directory isn't this clone's own <common dir>/hooks (a
#      core.hooksPath, or a symlinked hooks directory): a notice, exit 0
#   3. a pre-commit hook shirabe didn't write (a symlink, anything that isn't
#      a regular file, or a file without shirabe's exact header line): a
#      notice, exit 0, the hook and anything it links to left unchanged
#   4. no pre-commit hook: install it
#   5. a shirabe hook: refresh it only when its bytes differ from a freshly
#      generated one; silent when they match
# An install error exits non-zero with install-hooks' own stderr. Every
# install-hooks call runs the binary step 1 checked, never `shirabe` by name.
#
# Needs git 2.31 or later (rev-parse --path-format).
set -euo pipefail
unset GIT_DIR GIT_WORK_TREE GIT_COMMON_DIR GIT_INDEX_FILE

top=$(git rev-parse --show-toplevel)
bin=$(command -v shirabe 2>/dev/null || true)
case "$bin" in
  /*) bindir=$(cd "$(dirname "$bin")" && pwd -P) ;;
  *) bindir="" ;;
esac
case "$bindir/" in
  /|"$top"/*) bin="" ;;
esac
if [ -z "$bin" ]; then
  echo "shirabe not on PATH; pre-commit hook not installed (install it with: tsuku install tsukumogami/shirabe)"
  exit 0
fi

hooks=$(git rev-parse --path-format=absolute --git-path hooks)
common=$(git rev-parse --path-format=absolute --git-common-dir)
if [ "$hooks" != "$common/hooks" ] || [ -L "$hooks" ]; then
  echo "hooks directory $hooks is not this clone's own hooks directory; shirabe pre-commit hook not installed"
  exit 0
fi

header='# shirabe pre-commit hook -- generated by `shirabe install-hooks`.'
hook="$hooks/pre-commit"
if [ -L "$hook" ] || { [ -e "$hook" ] && { [ ! -f "$hook" ] || ! grep -qxF "$header" "$hook"; }; }; then
  echo "a pre-commit hook is already present; shirabe pre-commit hook not installed"
  exit 0
fi

if [ ! -e "$hook" ]; then
  "$bin" install-hooks >/dev/null
  echo "installed shirabe pre-commit hook"
  exit 0
fi

scratch=$(mktemp -d)
trap 'rm -rf -- "$scratch"' EXIT
git -C "$scratch" init -q
git -C "$scratch" config core.hooksPath "$scratch/.git/hooks"
( cd "$scratch" && "$bin" install-hooks --force >/dev/null )
if cmp -s "$scratch/.git/hooks/pre-commit" "$hook"; then
  exit 0
fi
"$bin" install-hooks --force >/dev/null
echo "refreshed shirabe pre-commit hook"
